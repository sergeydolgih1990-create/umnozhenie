/* Экран «Как устроены награды»: для родителя. Все числа берутся из тех же настроек, что и в игре. */
(function (U) {
  'use strict';

  const ui = U.ui, A = U.art, ic = A.icon, S = U.score;
  const pl = U.plural;
  const stars = (n) => n + ' ' + pl(n, 'звезда', 'звезды', 'звёзд');

  U.screens.help = function () {
    const p = U.player(), theme = (p && p.theme) || 'space', T = U.THEMES[theme], B = S.BONUS, V = U.VOICE_MODE;
    const sec = (title, icon, body) => `<div class="card help-sec"><h3>${ic(icon)}${title}</h3>${body}</div>`;
    const row = (what, n) => `<tr><td>${what}</td><td class="num">${n}</td></tr>`;

    const earn = `<p>Звёзды начисляются после каждого сохранённого раунда и идут сразу в два счёта:
      <b>баланс</b> — его тратят на призы, и <b>опыт</b> — от него растёт уровень. Покупка приза уменьшает только баланс,
      поэтому от покупок уровень не падает.${V ? ' Звёзды начисляются одинаково, отвечает ли ребёнок вслух или на клавиатуре.' : ''}</p>
      <table class="help-table"><tbody>
        ${row('Каждый верный ответ', '+' + B.correct)}
        ${row('Верный ответ в «Работе над ошибками»', '+' + B.correct * B.trainingMult)}
        ${row('Раунд без ошибок (от ' + B.cleanMin + ' примеров)', '+' + B.clean)}
        ${row('Новый рекорд пакета, если рекорд уже был', '+' + B.record)}
        ${row('Новая золотая клетка на карте таблицы', '+' + B.gold)}
        ${row('Кубок за строку, например «Повелитель семёрки»', '+' + B.cup)}
        ${row('Кубок «Вся таблица»', '+' + B.all)}
        ${row('Задание недели', '+' + B.quest)}
      </tbody></table>
      <p class="muted">За раунд с паузой и за разовый раунд звёзды начисляются, но в рекорды такой раунд не попадает. Если родитель
      удаляет раунд из истории, звёзды за него снимаются и с баланса, и с опыта (ниже нуля не уходят) — это способ убрать
      пробные раунды.</p>`;

    const prizes = `<p>Призы и их цену в звёздах задаёт родитель в разделе для родителей (замок на главном экране).
      Ребёнок копит звёзды и нажимает «Купить», покупку подтверждает родитель PIN-кодом.</p>
      <p class="muted">Ориентир: один «Школьный блиц» без ошибок — около 20 звёзд. Маленький приз — около 100 звёзд
      (неделя занятий), большой — около 500.</p>`;

    let levels = '';
    for (let lv = 1; lv <= U.LEVELS.length; lv++) {
      const st = U.stageOf(lv), first = (lv - 1) % 3 === 0;
      levels += `<tr${first ? ' class="stage-start"' : ''}><td class="num">${lv}</td><td>${U.LEVELS[lv - 1]}</td><td>${T.titles[st - 1]}</td></tr>`;
    }
    const heroes = [1, 2, 3, 4, 5].map((s) => `<div class="help-hero" data-theme="${theme}">${A.hero(theme, s)}<b>${T.hero[s - 1]}</b><span>уровни ${s * 3 - 2}–${s * 3}</span></div>`).join('');
    const lvl = `<p>Уровень растёт от опыта — всех заработанных звёзд за всё время. Всего ${U.LEVELS.length} уровней.
      Каждые три уровня герой меняет облик, а игрок получает новое звание: всего пять ступеней. У каждого игрока своя
      тема; ниже — герой темы «${T.name}» на каждой ступени.</p>
      <div class="help-heroes">${heroes}</div>
      <table class="help-table levels"><thead><tr><th>Уровень</th><th>Нужно звёзд всего</th><th>Звание</th></tr></thead><tbody>${levels}</tbody></table>`;

    const map = `<p>У каждого примера своя клетка — отдельно для умножения и для деления.</p>
      <ul class="help-list">
        <li><span class="sw c1"></span><b>Бронза</b> — пример решён верно.</li>
        <li><span class="sw c2"></span><b>Серебро</b> — решён верно 3 раза.</li>
        <li><span class="sw c3"></span><b>Золото</b> — 3 верных ответа подряд, каждый быстрее ${S.FAST_MS / 1000} секунд.</li>
      </ul>
      <p>Ошибка опускает клетку на ступень вниз — её нужно заработать заново. Строка целиком в золоте даёт кубок
      (+${B.cup}), вся таблица — главный кубок (+${B.all}).${V ? ' В диктанте на бумаге времени нет, поэтому там клетки растут только до серебра.' : ''}</p>`;

    const records = `<p>Рекорды ведутся по каждому пакету отдельно${V ? ': для ответов вслух и для ответов на клавиатуре — их нечестно сравнивать между собой' : ''}. Если у пакета поменялся темп, старые результаты остаются в истории, но с новыми не сравниваются.</p>
      <p>Лучше тот раунд, где больше верных. При равенстве — тот, что быстрее, а если и тут поровну — более ранний.
      В «Минуте» считается число верных, в «До первой ошибки» — длина серии.</p>`;

    const quest = `<p>Неделя — с понедельника по воскресенье. Нужно сыграть 3 любых раунда и пройти «Школьный блиц» без ошибок.
      За выполнение — +${B.quest} звёзд и огонёк в серии недель: сколько недель подряд задание выполнено.</p>`;

    const training = `<p>Сюда попадают примеры, на которых за последние 10 раундов была ошибка или ответ дольше
      ${S.SLOW_MS / 1000} секунд. Пример уходит из списка, когда на него 3 раза подряд, в разных раундах, ответили верно и быстро.
      Звёзды за верные ответы здесь двойные.</p>`;

    const self = `<p>${V ? 'Переключатель «Ответ вслух / Ответ на клавиатуре» — на экране выбора пакета и в карточке игрока. «Вслух»: ребёнок говорит ответ, взрослый жмёт «Верно» или «Неверно», после раунда можно поправить отметки. «На клавиатуре»: ребёнок' : 'Ребёнок'}
      набирает ответ и нажимает ✓, тренажёр проверяет сам и сразу даёт следующий пример. Если время вышло, набранный ответ
      засчитывается как есть, пустой — как ошибка «время вышло». После раунда сразу итог, ошибки — с тем, что ребёнок набрал.</p>
      <p class="muted">В «Диктанте на слух» пример только звучит, а ответы складываются в строку через запятую — как в тетради.</p>`;

    const term = (w, d) => `<li><b>${w}</b> — ${d}</li>`;
    const glossary = `<ul class="help-list terms">
      ${term('Раунд', 'одна игра: от отсчёта 3-2-1 до итога. В историю попадает только сохранённый раунд')}
      ${term('Пакет', 'готовый набор условий раунда: сколько примеров, какие, сколько секунд на пример. «Школьный блиц», «Минута» и другие')}
      ${term('Разовый раунд', 'раунд со своими условиями без сохранения пакета («Свой раунд» → «Сыграть»)')}
      ${term('Рекорд', 'лучший результат в пакете: больше верных, при равенстве — быстрее или раньше')}
      ${term('Карта таблицы', 'все примеры таблицы клетками; клетка загорается бронзой, серебром и золотом по мере того, как пример выучен')}
      ${term('Кубок', 'награда, когда целая строка карты стала золотой, например все примеры на 7')}
      ${term('Задание недели', 'три раунда за неделю и «Школьный блиц» без ошибок')}
      ${term('Работа над ошибками', 'пакет из трудных примеров; на итоге раунда ошибки тоже показаны')}
    </ul>`;
    return `<div class="screen scroll">
      <div class="topbar"><button class="icon-btn" data-act="back" aria-label="Назад">${ic('back')}</button>
        <div class="grow who"><div class="name">Как устроены награды</div><div class="title">Для родителей</div></div></div>
      ${sec('Звёзды', 'star', earn)}
      ${sec('Призы', 'gift', prizes)}
      ${sec('Уровни и герой', 'trophy', lvl)}
      ${sec('Карта таблицы', 'map', map)}
      ${sec('Рекорды', 'trophy', records)}
      ${sec('Задание недели', 'flame', quest)}
      ${sec('Работа над ошибками', 'target', training)}
      ${sec(V ? 'Ответ вслух или на клавиатуре' : 'Как отвечать', 'check', self)}
      ${sec('Словарик', 'list', glossary)}
    </div>`;
  };
  U.actions.help = (ds) => U.go('help', { from: ds && ds.v });
  U.helpStars = stars;
})(window.U = window.U || {});
