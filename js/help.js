/* Экран «Как устроены награды»: для родителя. Все числа берутся из тех же настроек, что и в игре. */
(function (U) {
  'use strict';

  const A = U.art, ic = A.icon, S = U.score;
  const pl = U.plural;
  const stars = (n) => n + ' ' + pl(n, 'звезда', 'звезды', 'звёзд');

  U.screens.help = function () {
    const p = U.player(), theme = (p && p.theme) || 'space', T = U.THEMES[theme], B = S.BONUS, V = U.VOICE_MODE, Lv = U.levels;
    const sec = (title, icon, body) => `<div class="card help-sec"><h3>${ic(icon)}${title}</h3>${body}</div>`;
    const row = (what, n) => `<tr><td>${what}</td><td class="num">${n}</td></tr>`;

    /* Уровни и испытания */
    const examList = Lv.EXAMS.map((e) => {
      const nb = (x) => x.replace(/ ([×÷+]) /g, '\u00a0$1\u00a0');
      const what = e.kind === 'each' ? (e.voice ? nb('на каждый пример темп + ' + U.num(e.extra) + '\u00a0с: время, чтобы голос прочитал пример') : 'на каждый пример не больше темпа')
        : e.kind === 'total' ? nb('все ' + (e.mul + e.div) + ' примеров за 20 × темп')
          : e.kind === 'minute' ? nb('за минуту не меньше 60 ÷ темп верных ответов (с округлением)')
            : 'серия верных подряд — от ' + Lv.SERIES[0] + ' на 1-м уровне до ' + Lv.SERIES[Lv.MAX - 1] + ' на 10-м, на каждый не больше темпа';
      return `<li><b>${e.name}</b> — ${what}</li>`;
    }).join('');
    let paces = '';
    for (let lv = 1; lv <= Lv.MAX; lv++) {
      const st = U.stageOf(lv), tt = (id) => Lv.terms(Lv.byId(id), lv);
      paces += `<tr><td class="num">${lv}</td><td>${U.num(Lv.pace(lv))} с</td><td>${S.fmtTime(tt('mulonly').totalMs)}</td><td>${tt('minute').need}</td><td>${tt('streak').series}</td><td>${T.titles[st - 1]}</td></tr>`;
    }
    const heroes = T.hero.map((name, i) => `<div class="help-hero" data-theme="${theme}">${A.hero(theme, i + 1)}<b>${name}</b><span>уровень ${i + 1}</span></div>`).join('');
    const levels = `<p>Уровень открывают <b>испытания</b>, а не звёзды. У каждого уровня свой <b>темп</b> — сколько секунд даётся
      на пример: на 1-м уровне ${Lv.pace(1)} ${U.secWord(Lv.pace(1))}, на ${Lv.SCHOOL_LEVEL}-м — ${Lv.SCHOOL_PACE} ${U.secWord(Lv.SCHOOL_PACE)}, как в школе,
      на ${Lv.MAX}-м — ${Lv.pace(Lv.MAX)} ${U.secWord(Lv.pace(Lv.MAX))}. Чтобы открыть следующий уровень,
      нужно пройти все ${Lv.EXAMS.length} испытаний текущего — <b>без единой ошибки</b> и в лимит времени.</p>
      <ul class="help-list terms">${examList}</ul>
      <p class="muted">Испытание можно проходить сколько угодно раз; засчитывается первое удачное на текущем уровне. Если в раунде
      была пауза, испытание не засчитывается. В испытании «До первой ошибки» ошибка сразу заканчивает раунд, в остальных раунд доигрывается
      до конца — это тоже тренировка.</p>
      <table class="help-table paces"><thead><tr><th>Ур.</th><th>Темп</th><th>20 примеров за</th><th>Минута: верных</th><th>Серия</th><th>Звание</th></tr></thead><tbody>${paces}</tbody></table>
      <p>На каждом уровне герой меняет облик, а игрок получает новое звание — всего ${T.hero.length} обликов. У каждого игрока
      своя тема; ниже — герой темы «${T.name}» на каждом уровне.</p>
      <div class="help-heroes">${heroes}</div>`;

    /* Звёзды и призы */
    const earn = `<p>Звёзды — это «деньги» тренажёра: их копят и тратят на призы. Уровень от звёзд не зависит. Звёзды начисляются
      после каждого сохранённого раунда — и за испытания, и за тренировки.</p>
      <table class="help-table"><tbody>
        ${row('Каждый верный ответ', '+' + B.correct)}
        ${row('Верный ответ в «Работе над ошибками»', '+' + B.correct * B.trainingMult)}
        ${row('Раунд без ошибок (от ' + B.cleanMin + ' примеров)', '+' + B.clean)}
        ${row('Испытание пройдено (впервые на уровне)', '+' + B.exam)}
        ${row('Открыт новый уровень', '+' + B.level)}
        ${row('Новый рекорд тренировки, если рекорд уже был', '+' + B.record)}
        ${row('Новая золотая клетка на карте таблицы', '+' + B.gold)}
        ${row('Кубок за строку, например «Повелитель семёрки»', '+' + B.cup)}
        ${row('Кубок «Вся таблица»', '+' + B.all)}
        ${row('Задание недели', '+' + B.quest)}
      </tbody></table>
      <p class="muted">Если родитель удаляет раунд из истории, звёзды за него снимаются (ниже нуля баланс не уходит), а пройденные
      испытания и карта таблицы остаются. Так можно убрать пробные раунды.</p>`;
    const prizes = `<p>Призы и их цену в звёздах задаёт родитель в разделе для родителей (замок на главном экране).
      Ребёнок копит звёзды и нажимает «Купить», покупку подтверждает родитель PIN-кодом.</p>
      <p class="muted">Ориентир: один «Школьный блиц» без ошибок — около 20 звёзд, пройденное испытание — ещё +${B.exam}.
      Маленький приз — около 100 звёзд (неделя занятий), большой — около 500.</p>`;

    const map = `<p>У каждого примера своя клетка — отдельно для умножения и для деления.</p>
      <ul class="help-list">
        <li><span class="sw c1"></span><b>Бронза</b> — пример решён верно.</li>
        <li><span class="sw c2"></span><b>Серебро</b> — решён верно 3 раза.</li>
        <li><span class="sw c3"></span><b>Золото</b> — 3 верных ответа подряд, каждый быстрее ${S.FAST_MS / 1000} секунд.</li>
      </ul>
      <p>Ошибка опускает клетку на ступень вниз — её нужно заработать заново. Строка целиком в золоте даёт кубок
      (+${B.cup}), вся таблица — главный кубок (+${B.all}).</p>`;

    const training = `<p><b>Тренировки</b> — обычные пакеты в своём темпе: «Школьный блиц» по 7 секунд, «Блиц-мастер» по 5 и другие.
      На уровень они не влияют, но в них ведутся рекорды и начисляются звёзды.</p>
      <p>Рекорд — лучший результат в пакете: больше верных, при равенстве — быстрее, а если и тут поровну — раньше. В «Минуте»
      считается число верных, в «До первой ошибки» — длина серии. Если у пакета поменялся темп, старые результаты остаются в истории,
      но с новыми не сравниваются.</p>
      <p><b>Работа над ошибками</b> — пакет из примеров, где за последние 10 раундов была ошибка или ответ дольше
      ${S.SLOW_MS / 1000} секунд. Пример уходит из списка после трёх верных и быстрых ответов подряд в разных раундах.
      Звёзды здесь двойные.</p>`;

    const quest = `<p>Неделя — с понедельника по воскресенье. Нужно сыграть 3 любых раунда и пройти «Школьный блиц» без ошибок
      (испытание тоже считается). За выполнение — +${B.quest} звёзд и огонёк в серии недель.</p>`;

    const self = `<p>${V ? 'Переключатель «Ответ вслух / Ответ на клавиатуре» — на экране тренировок и в карточке игрока. «Вслух»: ребёнок говорит ответ, взрослый жмёт «Верно» или «Неверно». «На клавиатуре»: ребёнок' : 'Ребёнок'}
      набирает ответ и нажимает ✓, тренажёр проверяет сам и сразу даёт следующий пример. Если время вышло, набранный ответ
      засчитывается как есть, пустой — как ошибка «время вышло». После раунда сразу итог, ошибки — с тем, что ребёнок набрал.</p>
      <p class="muted">В «Диктанте на слух» пример только звучит, а ответы складываются в строку через запятую — как в тетради.</p>`;

    const term = (w, d) => `<li><b>${w}</b> — ${d}</li>`;
    const glossary = `<ul class="help-list terms">
      ${term('Раунд', 'одна игра: от отсчёта 3-2-1 до итога')}
      ${term('Испытание', 'раунд в темпе уровня, который надо пройти без ошибок; 7 испытаний открывают следующий уровень')}
      ${term('Темп', 'сколько секунд даётся на один пример на этом уровне')}
      ${term('Тренировка', 'обычный пакет в своём темпе; даёт звёзды и рекорды, на уровень не влияет')}
      ${term('Пакет', 'готовый набор условий тренировки: сколько примеров, какие, сколько секунд на пример')}
      ${term('Рекорд', 'лучший результат в пакете тренировки')}
      ${term('Карта таблицы', 'все примеры таблицы клетками: бронза, серебро, золото — по мере того, как пример выучен')}
      ${term('Кубок', 'награда, когда целая строка карты стала золотой, например все примеры на 7')}
      ${term('Задание недели', 'три раунда за неделю и «Школьный блиц» без ошибок')}
    </ul>`;

    return `<div class="screen scroll">
      <div class="topbar"><button class="icon-btn" data-act="back" aria-label="Назад">${ic('back')}</button>
        <div class="grow who"><div class="name">Как устроены награды</div><div class="title">Для родителей</div></div></div>
      ${sec('Уровни и испытания', 'trophy', levels)}
      ${sec('Звёзды', 'star', earn)}
      ${sec('Призы', 'gift', prizes)}
      ${sec('Карта таблицы', 'map', map)}
      ${sec('Тренировки и рекорды', 'target', training)}
      ${sec('Задание недели', 'flame', quest)}
      ${sec('Как отвечать', 'check', self)}
      ${sec('Словарик', 'list', glossary)}
    </div>`;
  };
  U.actions.help = (ds) => U.go('help', { from: ds && ds.v });
  U.helpStars = stars;
})(window.U = window.U || {});
