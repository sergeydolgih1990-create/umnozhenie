  U.STAGES = 10;
  U.stageOf = function (level) { return Math.min(U.STAGES, Math.max(1, level | 0 || 1)); };
  U.titleOf = function (theme, level) { return U.THEMES[theme].titles[U.stageOf(level) - 1]; };
