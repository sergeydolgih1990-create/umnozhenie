/* Темы, герои, звания и пороги уровней */
(function (U) {
  'use strict';

  U.THEMES = {
    space: {
      name: 'Космос',
      hero: ['Картонная ракета', 'Ракета', 'Ракета с ускорителями', 'Космолёт', 'Звездолёт'],
      titles: ['Кадет', 'Пилот', 'Штурман', 'Капитан', 'Адмирал галактики']
    },
    dragon: {
      name: 'Драконы',
      hero: ['Яйцо дракона', 'Дракончик вылупился', 'Дракончик', 'Дракон', 'Великий дракон'],
      titles: ['Хранитель яйца', 'Друг дракончика', 'Наездник', 'Укротитель драконов', 'Повелитель драконов']
    },
    pirate: {
      name: 'Пираты',
      hero: ['Плот', 'Лодка', 'Шхуна', 'Бриг', 'Фрегат'],
      titles: ['Юнга', 'Матрос', 'Боцман', 'Капитан', 'Адмирал морей']
    }
  };

  // Старая система «уровень от звёзд» — осталась только для страницы макетов (mockups.html).
  // В тренажёре уровни открываются испытаниями: js/levels.js.
  U.LEVELS = [0, 30, 70, 120, 180, 250, 330, 420, 520, 640, 780, 940, 1120, 1320, 1550];

  U.levelOf = function (xp) {
    let level = 1;
    while (level < U.LEVELS.length && xp >= U.LEVELS[level]) level++;
    return level;
  };
  // Ступень героя: новая каждые 2 уровня из 10
  U.stageOf = function (level) { return Math.min(5, Math.max(1, Math.ceil(level / 2))); };
  U.titleOf = function (theme, level) { return U.THEMES[theme].titles[U.stageOf(level) - 1]; };
})(window.U = window.U || {});
